#!/usr/bin/env node
/**
 * Writes src/fixtures.ts: one key pair per asymmetric algorithm and a token
 * for each, signed by Node's crypto — an implementation independent of the
 * library, so the app proves interop on the device, not just a round trip.
 *
 * Run with `npm run fixtures`. The keys are throwaway test keys.
 */
import crypto from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const b64u = (data) => Buffer.from(data).toString('base64url');
const gen = (type, options) => crypto.generateKeyPairSync(type, options);
const pem = (key) => key.export(key.type === 'public' ? { type: 'spki', format: 'pem' } : { type: 'pkcs8', format: 'pem' });

const pairs = {
  rsa: gen('rsa', { modulusLength: 2048 }),
  p256: gen('ec', { namedCurve: 'prime256v1' }),
  p384: gen('ec', { namedCurve: 'secp384r1' }),
  p521: gen('ec', { namedCurve: 'secp521r1' }),
  k1: gen('ec', { namedCurve: 'secp256k1' }),
  ed: gen('ed25519'),
};

function nodeSign(alg, key, payload) {
  const input = `${b64u(JSON.stringify({ alg, typ: 'JWT' }))}.${b64u(JSON.stringify(payload))}`;
  if (alg.startsWith('HS')) {
    return `${input}.${b64u(crypto.createHmac(`sha${alg.slice(2)}`, key).update(input).digest())}`;
  }
  let options = key;
  if (alg.startsWith('PS')) {
    options = { key, padding: crypto.constants.RSA_PKCS1_PSS_PADDING, saltLength: Number(alg.slice(2)) / 8 };
  } else if (alg.startsWith('ES')) {
    options = { key, dsaEncoding: 'ieee-p1363' };
  }
  const hash = alg === 'EdDSA' ? null : `sha${alg.slice(2, 5)}`;
  return `${input}.${b64u(crypto.sign(hash, Buffer.from(input), options))}`;
}

const secret = crypto.randomBytes(32).toString('base64url');
const cases = [
  ['RS256', 'rsa'],
  ['PS256', 'rsa'],
  ['ES256', 'p256'],
  ['ES384', 'p384'],
  ['ES512', 'p521'],
  ['ES256K', 'k1'],
  ['EdDSA', 'ed'],
].map(([alg, kind]) => ({
  alg,
  privatePem: pem(pairs[kind].privateKey),
  publicPem: pem(pairs[kind].publicKey),
  nodeToken: nodeSign(alg, pairs[kind].privateKey, { sub: `node-${alg}` }),
}));

// Deterministic algorithms sign the same bytes on every implementation: the
// device must reproduce these tokens exactly. sign() writes { alg, typ } and
// appends iat after the payload, so Node signs the same JSON here.
const referenceIat = 1700000000;
const referencePayload = { sub: 'reference', iat: referenceIat };
const reference = {
  iat: referenceIat,
  tokens: {
    HS256: nodeSign('HS256', secret, referencePayload),
    RS256: nodeSign('RS256', pairs.rsa.privateKey, referencePayload),
    EdDSA: nodeSign('EdDSA', pairs.ed.privateKey, referencePayload),
  },
};

const fixtures = { secret, hs256NodeToken: nodeSign('HS256', secret, { sub: 'node-HS256' }), cases, reference };
const out = fileURLToPath(new URL('../src/fixtures.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/make-fixtures.mjs on ${new Date().toISOString().slice(0, 10)}. Throwaway test keys.\n` +
    `export const fixtures = ${JSON.stringify(fixtures, null, 2)} as const;\n`,
);
console.log(`wrote ${out}`);
